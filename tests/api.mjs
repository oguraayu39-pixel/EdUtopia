import assert from 'node:assert/strict';
import {api} from '../worker/api.js';
import fs from 'node:fs';
const data=JSON.parse(fs.readFileSync(new URL('../data/curriculum.json',import.meta.url)));
const request=(path,body)=>new Request('https://example.test'+path,body===undefined?{}:{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
let result=await api(request('/api/curriculum'),{},data);
assert.equal((await result.json()).source,'local demo data');
assert.equal((await api(request('/api/research'),{},data)).status,405);
assert.equal((await api(request('/api/research',{query:''}),{},data)).status,400);
assert.equal((await api(request('/api/research',{query:'a'.repeat(501)}),{},data)).status,400);
const realFetch=globalThis.fetch;let observed;
globalThis.fetch=async(url,init)=>{observed={url,init};return new Response(JSON.stringify({results:[{title:'A source',url:'https://example.org',snippet:'Evidence'}]}))};
result=await api(request('/api/research',{query:'waste research'}),{},data);
assert.equal((await result.json()).results[0].title,'A source');
assert.equal(observed.url,'https://api.keenable.ai/v1/search/public');
assert.equal(observed.init.headers['X-Keenable-Title'],'EDUTOPIA Learning Atlas');
await api(request('/api/research',{query:'waste research'}),{KEENABLE_API_KEY:'test-only'},data);
assert.equal(observed.url,'https://api.keenable.ai/v1/search');assert.equal(observed.init.headers['X-API-Key'],'test-only');
globalThis.fetch=async()=>new Response('{}',{status:429});
result=await api(request('/api/research',{query:'waste research'}),{},data);assert.equal(result.status,503);assert.match((await result.json()).error,/limit/);
globalThis.fetch=async()=>{throw Error('unreachable')};
assert.equal((await api(request('/api/research',{query:'waste research'}),{},data)).status,503);
result=await api(request('/api/curriculum'),{SNOWFLAKE_ACCOUNT_URL:'https://example.snowflakecomputing.com',SNOWFLAKE_TOKEN:'test-only'},data);assert.equal((await result.json()).source,'local demo data');
globalThis.fetch=realFetch;
console.log('API checks passed: curriculum fallback, query validation, public/keyed routing, rate-limit and network handling.');
